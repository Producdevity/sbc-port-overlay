"""Convert the pinned Spleen ASCII subset without a font-library dependency."""
from pathlib import Path
import hashlib

root = Path(__file__).resolve().parents[1]
source = root / "vendor/spleen/spleen-5x8.bdf"
if hashlib.sha256(source.read_bytes()).hexdigest() != "31cc2fc353e59e2ec99fd2d7c34962c99a9ad56ac4de39555436be492f6dfb24":
    raise ValueError("font input differs from the pinned source")
glyphs = {}
code = -1
bitmap = False
rows = []
for line in source.read_text().splitlines():
    if line.startswith("ENCODING "):
        code = int(line.split()[1])
    elif line == "BITMAP":
        bitmap = True
        rows = []
    elif line == "ENDCHAR":
        if 32 <= code <= 126:
            assert len(rows) == 8
            glyphs[code] = rows
        bitmap = False
    elif bitmap:
        rows.append(int(line, 16))
assert len(glyphs) == 95
out = ["/* SPDX-License-Identifier: BSD-2-Clause */",
       "/* Spleen: Copyright (c) 2018-2024 Frederic Cambus. See vendor/spleen/LICENSE. */",
       "/* Generated by tools/font_convert.py; do not edit. */",
       "static const unsigned char spo_font[95][8] = {"]
for code in range(32, 127):
    out.append("    {" + ",".join(f"0x{x:02x}" for x in glyphs[code]) + "},")
out.append("};\n")
(root / "src/font_data.h").write_text("\n".join(out))
print(hashlib.sha256(source.read_bytes()).hexdigest())
