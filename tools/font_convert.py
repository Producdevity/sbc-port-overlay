"""Convert the pinned Spleen ASCII subsets without a font-library dependency."""
from pathlib import Path
import hashlib

root = Path(__file__).resolve().parents[1]
FONTS = {
    (6, 12): "f40e935bdd194976d30ef296920d5ccca29eb84bb7b3459a88fe7932fa8ba872",
    (8, 16): "b2b05484ba4380c9c6854cc57637235a9fb039c65b5ba38a65289540f8fab7dc",
    (12, 24): "eb690d1dd190e21ae31f800e63fe1188409e3d94a11da222196de0777ed8c9e8",
    (16, 32): "3b6ae73ef1dd3c78bad873697c18b15df82d8e5c0258114fda401556e01d0e67",
}


def convert(width: int, height: int, digest: str) -> list[list[int]]:
    source = root / f"vendor/spleen/spleen-{width}x{height}.bdf"
    if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
        raise ValueError(f"{source.name} differs from the pinned source")
    stride = (width + 7) // 8
    glyphs = {}
    code = -1
    bitmap = False
    rows = []
    for line in source.read_text().splitlines():
        if line.startswith("ENCODING "):
            code = int(line.split()[1])
        elif line == "BITMAP":
            bitmap = True
            rows = []
        elif line == "ENDCHAR":
            if 32 <= code <= 126:
                assert len(rows) == height
                glyphs[code] = [b for row in rows for b in row.to_bytes(stride, "big")]
            bitmap = False
        elif bitmap:
            assert len(line) == stride * 2
            rows.append(int(line, 16))
    assert len(glyphs) == 95
    return [glyphs[code] for code in range(32, 127)]


out = [
    "/* SPDX-License-Identifier: BSD-2-Clause */",
    "/* Spleen: Copyright (c) 2018-2024 Frederic Cambus. See vendor/spleen/LICENSE. */",
    "/* Generated by tools/font_convert.py; do not edit. */",
]
for (width, height), digest in FONTS.items():
    stride = (width + 7) // 8
    out.append(f"static const unsigned char spo_font_{width}x{height}[95][{stride * height}] = {{")
    for glyph in convert(width, height, digest):
        out.append("    {" + ",".join(f"0x{x:02x}" for x in glyph) + "},")
    out.append("};")
(root / "src/font_data.h").write_text("\n".join(out) + "\n")
